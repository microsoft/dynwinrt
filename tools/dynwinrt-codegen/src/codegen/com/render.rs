/// A rendered classic-COM output: primary `.js` + `.d.ts` for the interface,
/// plus zero or more sibling files (one `.js` + `.d.ts` per referenced enum).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ComGeneratedOutput {
    pub js: String,
    pub dts: String,
    /// Additional files (filename → content). Includes each enum's `.js` and
    /// `.d.ts`. Stable-sorted by filename for deterministic output.
    pub extra_files: Vec<(String, String)>,
}

// ---------------------------------------------------------------------------
// Public entry
// ---------------------------------------------------------------------------

/// Generate the `.js` + `.d.ts` for a classic-COM interface.
///
/// `winmd_paths` is the semicolon-separated list of `.winmd` files loaded by
/// the generator. Interop `*Interop` interfaces consult these winmds FIRST
/// to resolve the projected WinRT runtime class's default IID; if that fails
/// (e.g. the caller only passed Win32 metadata), the generator falls back to
/// the NEWEST installed `UnionMetadata\<version>\Windows.winmd`. If the target
/// IID still cannot be resolved for a confirmed interop shape, generation
/// **fails loudly** with `Err(...)` — the generator must never emit a NULL
/// riid that would silently break the wrapper at runtime.
pub fn generate_com_interface_files(
    meta: &ComInterfaceMeta,
    winmd_paths: &str,
) -> Result<ComGeneratedOutput, String> {
    validate_com_abi(meta)?;
    validate_untyped_outputs(meta)?;

    // Detect whether this is a `*Interop` interface whose every method has the
    // `(HWND, [HSTRING…,] REFIID, out void**)` GetForWindow shape. Natural
    // signatures hide the REFIID + void** and return an explicit bridge value.
    let interop = detect_interop(meta, winmd_paths)?;

    let js = render_js(meta, interop.as_ref());
    let dts = render_dts(meta, interop.as_ref());

    // Per-enum sibling files (referenced by parameter types).
    let mut extra_files: Vec<(String, String)> = Vec::new();
    for en in &meta.referenced_enums {
        let (enum_js, enum_dts) = render_enum_files(en);
        extra_files.push((format!("{}.js", en.name), enum_js));
        extra_files.push((format!("{}.d.ts", en.name), enum_dts));
    }

    extra_files.sort_by(|a, b| a.0.cmp(&b.0));

    Ok(ComGeneratedOutput {
        js,
        dts,
        extra_files,
    })
}

// ---------------------------------------------------------------------------
// .js rendering
// ---------------------------------------------------------------------------

fn render_js(meta: &ComInterfaceMeta, interop: Option<&InteropInfo>) -> String {
    let iface = &meta.interface;
    let iid = &iface.iid;
    let name = &iface.name;

    let mut out = String::new();
    out.push_str("// Generated by dynwinrt-codegen — do not edit\n");

    // Imports (runtime + any referenced enums)
    let runtime_imports = if interop.is_some() {
        "DynCom, DynComMethodSig, DynWinRtValue, WinGuid"
    } else {
        "DynCom, DynComMethodSig, WinGuid"
    };
    out.push_str(&format!(
        "import {{ {runtime_imports} }} from '{}';\n",
        com_runtime_import_name()
    ));
    for en in enum_import_names(meta) {
        out.push_str(&format!("import {{ {} }} from './{}.js';\n", en, en));
    }
    out.push('\n');

    if has_string_buffer_method(meta) {
        out.push_str("function _normalizeStringBufferCount(value, name) {\n");
        out.push_str("    if (!Number.isInteger(value) || value <= 0) throw new TypeError(`${name} must be a positive integer`);\n");
        out.push_str("    return value;\n");
        out.push_str("}\n");
        out.push_str("function _decodeWideString(buffer) {\n");
        out.push_str("    let end = 0;\n");
        out.push_str(
            "    while (end + 1 < buffer.length && buffer.readUInt16LE(end) !== 0) end += 2;\n",
        );
        out.push_str("    return buffer.subarray(0, end).toString('utf16le');\n");
        out.push_str("}\n\n");
    }

    out.push_str(&format!(
        "export const IID_{name} = WinGuid.parse('{iid}');\n",
        name = name,
        iid = iid
    ));
    // For interop wrappers with a resolved target IID, also emit the target
    // interface IID as a private constant used by the getForWindow call.
    if let Some(info) = interop {
        if !info.target_iid.is_empty() {
            out.push_str(&format!(
                "const IID_{cls}_default = WinGuid.parse('{iid}');\n",
                cls = info.class_name,
                iid = info.target_iid,
            ));
        }
    }
    out.push('\n');

    // Interface registration is base-aware.
    let register_fn = if meta.is_iunknown_rooted {
        "registerIUnknownInterface"
    } else {
        "registerIInspectableInterface"
    };
    let registration_name = format!("{}.{}", iface.namespace, name);
    let cache_var = format!("_{name}Cache", name = name);
    let iface_var = format!("_{name}", name = name);
    out.push_str(&format!("let {cache_var};\n", cache_var = cache_var));
    out.push_str(&format!(
        "const {iface_var} = new Proxy({{}}, {{\n    get(_target, prop) {{\n        {cache_var} ??= DynCom.{register_fn}('{registration_name}', IID_{name})\n",
        iface_var = iface_var,
        cache_var = cache_var,
        name = name,
        registration_name = registration_name,
        register_fn = register_fn,
    ));
    for m in &iface.methods {
        out.push_str(&format!(
            "            .addMethod('{}', {})\n",
            m.name,
            build_method_sig_js(m)
        ));
    }
    // Trim trailing newline before closing the block, then close.
    if out.ends_with('\n') {
        out.truncate(out.len() - 1);
    }
    out.push_str(";\n");
    out.push_str(&format!(
        "        const value = {cache_var}[prop];\n        return typeof value === 'function' ? value.bind({cache_var}) : value;\n    }},\n}});\n",
        cache_var = cache_var,
    ));
    out.push('\n');

    // Class body
    out.push_str(&format!("export class {name} {{\n", name = name));
    out.push_str("    _obj;\n");
    out.push_str("    constructor(obj) { this._obj = obj; }\n");
    out.push_str(&format!(
        "    static _fromNative(obj) {{ return new {name}(obj); }}\n",
        name = name
    ));

    if let Some(ref clsid) = meta.coclass_clsid {
        // static create() — classic COM CLSID-based activation.
        out.push_str(&format!(
            "    /** Create a new `{name}` via `CoCreateInstance` on `CLSID_{cc}`. */\n",
            name = name,
            cc = meta.coclass_name.as_deref().unwrap_or("Coclass")
        ));
        out.push_str(&format!(
            "    static create() {{\n        const _obj = DynCom.coCreateInstance('{clsid}', IID_{name});\n        return new {name}(_obj);\n    }}\n",
            clsid = clsid,
            name = name,
        ));
    } else if let Some(info) = interop {
        if !info.class_namespace.is_empty() {
            // static create() — interop activation: activate the projected
            // WinRT runtime class's factory, then QI to the interop IID.
            let full_class_name = format!("{}.{}", info.class_namespace, info.class_name);
            out.push_str(&format!(
                "    /** Create a new `{name}` by activating the `{full_class_name}` factory and QI'ing to the interop. */\n",
                name = name,
                full_class_name = full_class_name,
            ));
            out.push_str(&format!(
                "    static create() {{\n        const factory = DynWinRtValue.activationFactory('{full_class_name}');\n        const _obj = factory.cast(IID_{name});\n        return new {name}(_obj);\n    }}\n",
                full_class_name = full_class_name,
                name = name,
            ));
        }
    }

    // Emit methods: natural interop shape when available, otherwise pass-through.
    if let Some(info) = interop {
        for im in &info.methods {
            emit_interop_method_js(&mut out, im, &iface_var, info);
        }
    } else {
        for m in &iface.methods {
            if let Some(natural_params) = method_is_interop_shape(m) {
                emit_dynamic_iid_method_js(&mut out, m, &natural_params, &iface_var);
            } else {
                emit_method_js(&mut out, m, &iface_var);
            }
        }
    }
    out.push_str("}\n");
    out
}

fn unwrap_method_result_js(
    method: &MethodMeta,
    result: MethodResult<'_>,
    expression: &str,
) -> String {
    if is_sys_free_string_owned(method, result) {
        format!("DynCom.takeBstr({expression})")
    } else if is_cotaskmem_owned(method, result)
        && !matches!(
            result.typ,
            TypeMeta::Struct { namespace, name, .. }
                if namespace == "Windows.Win32.Foundation"
                    && (name == "PWSTR" || name == "PSTR")
        )
    {
        format!("DynCom.adoptCoTaskMemPointer({expression})")
    } else {
        unwrap_return_js(result.typ, expression)
    }
}

fn validate_untyped_outputs(meta: &ComInterfaceMeta) -> Result<(), String> {
    for method in &meta.interface.methods {
        for (param_index, param) in method.params.iter().enumerate() {
            let is_untyped =
                param.direction == ParamDirection::Out && param.typ == TypeMeta::Object;
            let is_owned = method.owned_outputs.iter().any(|owned| {
                owned.param_index == param_index
                    && (owned.free_with.contains("CoTaskMemFree")
                        || (owned.free_with.contains("SysFreeString") && is_bstr(&param.typ)))
            });
            if is_untyped && !is_owned && method_is_interop_shape(method).is_none() {
                return Err(format!(
                    "{}.{}: untyped pointer output has no ownership projection",
                    meta.interface.name, method.name
                ));
            }
        }
    }
    Ok(())
}

fn emit_dynamic_iid_method_js(
    out: &mut String,
    method: &MethodMeta,
    natural_params: &[ParamMeta],
    interface_var: &str,
) {
    let mut surface_params = natural_params
        .iter()
        .enumerate()
        .map(|(index, param)| js_param_name(&param.name, index))
        .collect::<Vec<_>>();
    surface_params.push("iid".into());
    let mut args = natural_params
        .iter()
        .enumerate()
        .map(|(index, param)| wrap_arg_js(&param.typ, &js_param_name(&param.name, index)))
        .collect::<Vec<_>>();
    args.push("DynCom.iidPointer(_iid)".into());
    out.push_str(&format!(
        "    {name}({params}) {{\n",
        name = camel_case(&method.name),
        params = surface_params.join(", ")
    ));
    out.push_str("        const _iid = WinGuid.parse(iid);\n");
    out.push_str(&format!(
        "        const _raw = {interface_var}.method({slot}).invoke(this._obj, [{args}]);\n",
        slot = method.vtable_index,
        args = args.join(", ")
    ));
    out.push_str("        return DynCom.adoptComPointer(_raw, _iid);\n");
    out.push_str("    }\n");
}

fn build_method_sig_js(m: &MethodMeta) -> String {
    let mut parts = Vec::new();
    let string_buffer = string_buffer_pattern(m);
    for (idx, p) in m.params.iter().enumerate() {
        if p.direction == ParamDirection::In {
            parts.push(format!(".addIn({})", ts_type_expr_js(&p.typ)));
        } else if p.direction == ParamDirection::InOut {
            parts.push(format!(".addInOut({})", ts_type_expr_js(&p.typ)));
        } else if matches!(p.direction, ParamDirection::OutStringBuffer { .. }) {
            parts.push(".addIn(DynCom.pointerType())".to_string());
        } else if p.direction == ParamDirection::Out {
            if string_buffer.is_some_and(|(_, count_idx, _)| {
                idx > count_idx && is_optional_find_data_out_after_string_count(p)
            }) {
                parts.push(".addIn(DynCom.pointerType())".to_string());
            } else {
                parts.push(format!(".addOut({})", ts_type_expr_js(&p.typ)));
            }
        } else if p.direction == ParamDirection::OutFill {
            parts.push(format!(".addOutFill({})", ts_type_expr_js(&p.typ)));
        }
    }
    match &m.return_type {
        None => parts.push(".returnsVoid()".to_string()),
        Some(rt) if !is_hresult(rt) => {
            parts.push(format!(".returns({})", ts_type_expr_js(rt)));
        }
        _ => {}
    }
    if parts.is_empty() {
        "new DynComMethodSig()".to_string()
    } else {
        format!("new DynComMethodSig(){}", parts.join(""))
    }
}

fn emit_method_js(out: &mut String, m: &MethodMeta, iface_var: &str) {
    let camel = camel_case(&m.name);
    let in_params: Vec<(usize, &ParamMeta)> = m
        .params
        .iter()
        .enumerate()
        .filter(|(_, p)| p.direction.is_input())
        .collect();
    let results = method_results(m);
    let has_outfill = m
        .params
        .iter()
        .any(|p| p.direction == ParamDirection::OutFill);

    let param_list: Vec<String> = in_params
        .iter()
        .enumerate()
        .map(|(surface_i, (idx, p))| {
            let name = js_param_name(&p.name, surface_i);
            if let Some((_, count_idx, _)) = string_buffer_pattern(m) {
                if *idx == count_idx && string_buffer_param_is_optional(m, *idx) {
                    return format!("{name} = 260");
                }
                if *idx > count_idx && string_buffer_param_is_optional(m, *idx) {
                    return format!("{name} = 0");
                }
            }
            name
        })
        .collect();

    let args_exprs: Vec<String> = in_params
        .iter()
        .enumerate()
        .map(|(i, (_, p))| wrap_arg_js(&p.typ, &js_param_name(&p.name, i)))
        .collect();

    out.push_str(&format!(
        "    {camel}({params}) {{\n",
        camel = camel,
        params = param_list.join(", ")
    ));
    if let Some((buffer_idx, count_idx, encoding)) = string_buffer_pattern(m) {
        let count_surface_idx = in_params
            .iter()
            .position(|(idx, _)| *idx == count_idx)
            .expect("count param must be an input");
        let count_name = js_param_name(&m.params[count_idx].name, count_surface_idx);
        if encoding == StringEncoding::Ansi {
            out.push_str(
                "        throw new Error('PSTR out buffers are not yet decoded safely');\n",
            );
            out.push_str("    }\n");
            return;
        }
        let args: Vec<String> = m
            .params
            .iter()
            .enumerate()
            .filter_map(|(idx, p)| {
                if idx == buffer_idx {
                    Some("DynCom.pointer(_buffer)".to_string())
                } else if p.direction.is_input() {
                    let surface_idx = in_params
                        .iter()
                        .position(|(param_idx, _)| *param_idx == idx)
                        .expect("input param must have a surface index");
                    Some(wrap_arg_js(&p.typ, &js_param_name(&p.name, surface_idx)))
                } else if idx > count_idx && is_optional_find_data_out_after_string_count(p) {
                    Some("DynCom.pointer(0n)".to_string())
                } else {
                    None
                }
            })
            .collect();
        out.push_str(&format!(
            "        {count_name} = _normalizeStringBufferCount({count_name}, '{count_name}');\n"
        ));
        out.push_str(&format!(
            "        const _buffer = Buffer.alloc({count_name} * 2);\n"
        ));
        match results.len() {
            0 => out.push_str(&format!(
                "        {iface_var}.method({slot}).invoke(this._obj, [{args}]);\n",
                iface_var = iface_var,
                slot = m.vtable_index,
                args = args.join(", ")
            )),
            1 => out.push_str(&format!(
                "        const _out = {iface_var}.method({slot}).invoke(this._obj, [{args}]);\n",
                iface_var = iface_var,
                slot = m.vtable_index,
                args = args.join(", ")
            )),
            _ => out.push_str(&format!(
                "        const _out = {iface_var}.method({slot}).invokeAll(this._obj, [{args}]);\n",
                iface_var = iface_var,
                slot = m.vtable_index,
                args = args.join(", ")
            )),
        }
        out.push_str("        const _text = _decodeWideString(_buffer);\n");
        match results.len() {
            0 => out.push_str("        return _text;\n"),
            1 => out.push_str(&format!(
                "        return [_text, {}];\n",
                unwrap_method_result_js(m, results[0], "_out")
            )),
            _ => {
                let values = results
                    .iter()
                    .enumerate()
                    .map(|(index, result)| {
                        unwrap_method_result_js(m, *result, &format!("_out[{index}]"))
                    })
                    .collect::<Vec<_>>();
                out.push_str(&format!("        return [_text, {}];\n", values.join(", ")));
            }
        }
        out.push_str("    }\n");
        return;
    }
    // Project trailing `[out]` params as JS return values, mirroring how the
    // WinRT codegen already handles out-params (see
    // `codegen/javascript/project/methods.rs` — `is_multi_output` / `invokeAll`).
    // OutFill (caller-allocated buffers, e.g. GetPath(LPWSTR, cchMax)) are
    // NOT projected — see the TODO note below.
    if has_outfill {
        out.push_str("        // TODO: caller-allocated [out, sizeis] buffers are not yet projected as returns.\n");
    }
    match results.len() {
        0 => {
            out.push_str(&format!(
                "        {iface_var}.method({slot}).invoke(this._obj, [{args}]);\n",
                iface_var = iface_var,
                slot = m.vtable_index,
                args = args_exprs.join(", ")
            ));
        }
        1 => {
            out.push_str(&format!(
                "        const _out = {iface_var}.method({slot}).invoke(this._obj, [{args}]);\n",
                iface_var = iface_var,
                slot = m.vtable_index,
                args = args_exprs.join(", ")
            ));
            out.push_str(&format!(
                "        return {};\n",
                unwrap_method_result_js(m, results[0], "_out")
            ));
        }
        _ => {
            out.push_str(&format!(
                "        const _r = {iface_var}.method({slot}).invokeAll(this._obj, [{args}]);\n",
                iface_var = iface_var,
                slot = m.vtable_index,
                args = args_exprs.join(", ")
            ));
            let items: Vec<String> = results
                .iter()
                .enumerate()
                .map(|(i, result)| unwrap_method_result_js(m, *result, &format!("_r[{i}]")))
                .collect();
            out.push_str(&format!("        return [{}];\n", items.join(", ")));
        }
    }
    out.push_str("    }\n");
}

/// Emit an interop method: either natural (hide trailing REFIID + void**) or
/// plain (fall back to the normal classic-COM emission).
fn emit_interop_method_js(
    out: &mut String,
    im: &InteropMethod,
    iface_var: &str,
    info: &InteropInfo,
) {
    let Some(natural_params) = &im.natural_params else {
        if let Some(m) = &im.plain {
            if let Some(natural) = method_is_interop_shape(m) {
                emit_dynamic_iid_method_js(out, m, &natural, iface_var);
            } else {
                emit_method_js(out, m, iface_var);
            }
        }
        return;
    };
    let param_list: Vec<String> = natural_params
        .iter()
        .enumerate()
        .map(|(i, p)| js_param_name(&p.name, i))
        .collect();

    let mut arg_exprs: Vec<String> = natural_params
        .iter()
        .enumerate()
        .map(|(i, p)| wrap_arg_js(&p.typ, &js_param_name(&p.name, i)))
        .collect();

    // The synthesised REFIID pointer. When we have a resolved target IID we
    // pass the cached pointer; otherwise the method is unusable (still emitted
    // for completeness so `.d.ts` doesn't lie about the surface).
    let riid_arg = if !info.target_iid.is_empty() {
        format!("DynCom.iidPointer(IID_{}_default)", info.class_name)
    } else {
        "DynCom.pointer(0n)".to_string()
    };
    arg_exprs.push(riid_arg);

    out.push_str(&format!(
        "    {camel}({params}) {{\n",
        camel = im.camel,
        params = param_list.join(", "),
    ));
    if !info.target_iid.is_empty() {
        out.push_str(&format!(
            "        const _raw = {iface_var}.method({slot}).invoke(this._obj, [{args}]);\n",
            iface_var = iface_var,
            slot = im.vtable_index,
            args = arg_exprs.join(", "),
        ));
        out.push_str(&format!(
            "        const _out = DynCom.adoptComPointer(_raw, IID_{cls}_default);\n",
            cls = info.class_name,
        ));
        out.push_str("        return _out;\n");
    } else {
        // Fallback: no projection available. Return the raw object.
        out.push_str(&format!(
            "        return {iface_var}.method({slot}).invoke(this._obj, [{args}]);\n",
            iface_var = iface_var,
            slot = im.vtable_index,
            args = arg_exprs.join(", "),
        ));
    }
    out.push_str("    }\n");
}

