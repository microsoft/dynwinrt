fn render_enum_files(en: &ComEnumMeta) -> (String, String) {
    let name = en.name.as_str();
    // .js: a frozen object.
    let mut js = String::new();
    js.push_str("// Generated by dynwinrt-codegen — do not edit\n");
    js.push_str(&format!(
        "export const {name} = Object.freeze({{\n",
        name = name
    ));
    for member in &en.members {
        js.push_str(&format!(
            "    {}: {},\n",
            member.name,
            render_enum_value(&member.value, &en.underlying)
        ));
    }
    js.push_str("});\n");

    // .d.ts: emit a const object + companion type — matches the JS `Object.freeze({...})`
    // runtime shape and mirrors the WinRT enum generator (see
    // `codegen::javascript::render::declarations::render_enum_dts`). Using `const enum`
    // breaks under TS `isolatedModules`, so we intentionally avoid it.
    let mut dts = String::new();
    dts.push_str("// Generated by dynwinrt-codegen — do not edit\n");
    dts.push_str(&format!(
        "export type {name} = (typeof {name})[keyof typeof {name}];\n",
        name = name
    ));
    dts.push_str(&format!("export declare const {name}: {{\n", name = name));
    for member in &en.members {
        dts.push_str(&format!(
            "    readonly {}: {};\n",
            member.name,
            render_enum_value(&member.value, &en.underlying)
        ));
    }
    dts.push_str("};\n");

    (js, dts)
}

fn render_enum_value(value: &ComEnumValue, underlying: &TypeMeta) -> String {
    let suffix = if matches!(underlying, TypeMeta::I64 | TypeMeta::U64) {
        "n"
    } else {
        ""
    };
    match value {
        ComEnumValue::Signed(value) => format!("{value}{suffix}"),
        ComEnumValue::Unsigned(value) => format!("{value}{suffix}"),
    }
}

