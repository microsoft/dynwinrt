fn render_enum(definition: &EnumDefinition) -> (String, String) {
    let mut js = String::from("// Generated by dynwinrt-codegen - do not edit\n'use strict'\n");
    js.push_str(&format!("const {} = Object.freeze({{\n", definition.name));
    for member in &definition.members {
        js.push_str(&format!("  {}: {},\n", member.name, member.value));
    }
    js.push_str(&format!("}})\nexports.{0} = {0}\n", definition.name));

    let mut dts = String::from("// Generated by dynwinrt-codegen - do not edit\n");
    dts.push_str(&format!(
        "export type {0} = (typeof {0})[keyof typeof {0}]\nexport declare const {0}: {{\n",
        definition.name
    ));
    for member in &definition.members {
        dts.push_str(&format!("  readonly {}: {}\n", member.name, member.value));
    }
    dts.push_str("}\n");
    (js, dts)
}

