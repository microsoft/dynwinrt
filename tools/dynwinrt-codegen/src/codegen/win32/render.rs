fn collect_native_layouts(apis: &ProjectedApis) -> BTreeMap<String, NativeLayout> {
    let mut layouts = BTreeMap::new();
    for function in &apis.functions {
        for input in &function.inputs {
            if let InputExpression::NativeAggregate { layout, .. } = input {
                layouts
                    .entry(layout.name.clone())
                    .or_insert_with(|| layout.clone());
            }
        }
        if let Some(layout) = &function.runtime.return_aggregate {
            layouts
                .entry(layout.name.clone())
                .or_insert_with(|| layout.clone());
        }
    }
    layouts
}

fn native_layout_descriptor_js(layout: &NativeLayout) -> String {
    let descriptor = format!(
        "{{\"name\":\"{}.{}\",\"kind\":\"{}\",\"x86\":{},\"x64\":{},\"arm64\":{}}}",
        layout.namespace,
        layout.name,
        match layout.kind {
            super::ir::NativeAggregateKind::Struct => "struct",
            super::ir::NativeAggregateKind::Union => "union",
        },
        native_architecture_json(&layout.x86),
        native_architecture_json(&layout.x64),
        native_architecture_json(&layout.arm64),
    );
    format!(
        "'{}'",
        descriptor.replace('\\', "\\\\").replace('\'', "\\'")
    )
}

fn native_architecture_json(layout: &NativeArchitectureLayout) -> String {
    let fields = layout
        .fields
        .iter()
        .map(|field| {
            format!(
                "{{\"name\":\"{}\",\"offset\":{},\"count\":{},\"type\":{}}}",
                field.name,
                field.offset,
                field.count,
                native_field_type_json(&field.typ)
            )
        })
        .collect::<Vec<_>>()
        .join(",");
    format!(
        "{{\"size\":{},\"alignment\":{},\"fields\":[{}]}}",
        layout.size, layout.alignment, fields
    )
}

fn native_field_type_json(typ: &NativeFieldType) -> String {
    match typ {
        NativeFieldType::Scalar(scalar) => {
            format!("{{\"kind\":\"{}\"}}", native_scalar_name(*scalar))
        }
        NativeFieldType::Guid => "{\"kind\":\"guid\"}".into(),
        NativeFieldType::Pointer => "{\"kind\":\"pointer\"}".into(),
        NativeFieldType::Handle { cleanup } => format!(
            "{{\"kind\":\"handle\",\"cleanup\":\"{}\"}}",
            cleanup_name(*cleanup)
        ),
        NativeFieldType::Struct { name, layout, .. } => format!(
            "{{\"kind\":\"struct\",\"name\":\"{name}\",\"layout\":{}}}",
            native_architecture_json(layout)
        ),
        NativeFieldType::Union { name, layout, .. } => format!(
            "{{\"kind\":\"union\",\"name\":\"{name}\",\"layout\":{}}}",
            native_architecture_json(layout)
        ),
    }
}

