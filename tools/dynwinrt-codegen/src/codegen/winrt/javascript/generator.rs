use std::collections::HashSet;

use crate::meta::{ClassMeta, InterfaceMeta};
use crate::types::TypeMeta;

use crate::codegen::winrt::shared::structs::{
    collect_used_structs_from_class, collect_used_structs_from_iface,
};

/// Generate an index.ts that re-exports all generated types.
pub fn generate_index(
    classes: &[ClassMeta],
    interfaces: &[InterfaceMeta],
    enums: &[TypeMeta],
) -> String {
    let mut out = String::new();
    let mut seen: HashSet<String> = HashSet::new();
    out.push_str("// Generated by dynwinrt-codegen \u{2014} do not edit\n");
    // Export classes + their pack/unpack struct helpers.
    // IID_*, *_Type, *_PARAM_TYPES remain importable from individual module files.
    let mut sorted_classes: Vec<_> = classes.iter().collect();
    sorted_classes.sort_by(|a, b| a.name.cmp(&b.name));
    for class in sorted_classes {
        if seen.insert(class.name.clone()) {
            let struct_names: Vec<_> = collect_used_structs_from_class(class)
                .iter()
                .flat_map(|s| ts_pack_export_names(s))
                .filter(|n| seen.insert(n.clone()))
                .collect();
            if struct_names.is_empty() {
                out.push_str(&format!(
                    "export {{ {} }} from './{}.js';\n",
                    class.name, class.name
                ));
            } else {
                out.push_str(&format!(
                    "export {{ {}, {} }} from './{}.js';\n",
                    class.name,
                    struct_names.join(", "),
                    class.name
                ));
            }
        }
    }
    let mut sorted_ifaces: Vec<_> = interfaces.iter().collect();
    sorted_ifaces.sort_by(|a, b| a.name.cmp(&b.name));
    for iface in sorted_ifaces {
        if !seen.insert(iface.name.clone()) {
            continue;
        }
        // Skip delegates (IID + PARAM_TYPES only — internal plumbing)
        let is_delegate = iface.methods.iter().any(|m| m.name == ".ctor")
            && iface.methods.iter().any(|m| m.name == "Invoke");
        if is_delegate {
            continue;
        }
        let struct_names: Vec<_> = collect_used_structs_from_iface(iface)
            .iter()
            .flat_map(|s| ts_pack_export_names(s))
            .filter(|n| seen.insert(n.clone()))
            .collect();
        if struct_names.is_empty() {
            out.push_str(&format!(
                "export {{ {iname} }} from './{iname}.js';\n",
                iname = iface.name
            ));
        } else {
            out.push_str(&format!(
                "export {{ {iname}, {structs} }} from './{iname}.js';\n",
                iname = iface.name,
                structs = struct_names.join(", ")
            ));
        }
    }
    let mut sorted_enums: Vec<_> = enums.iter().collect();
    sorted_enums.sort_by(|a, b| {
        let name_a = match a {
            TypeMeta::Enum { name, .. } => name.as_str(),
            _ => "",
        };
        let name_b = match b {
            TypeMeta::Enum { name, .. } => name.as_str(),
            _ => "",
        };
        name_a.cmp(name_b)
    });
    for en in sorted_enums {
        if let TypeMeta::Enum { name, .. } = en {
            if seen.insert(name.clone()) {
                out.push_str(&format!("export {{ {} }} from './{}.js';\n", name, name));
            }
        }
    }
    out
}

/// ESM index → CJS barrel using `exports.X = new Proxy(...)` lazy loaders.
/// Direct `exports.X =` assignment is required for Electron's CJS lexer
/// (getter-form `Object.defineProperty` is silently ignored, breaking
/// `import { X }` from the barrel).
///
/// Proxy caveats: `instanceof`, `JSON.stringify`, `Object.freeze`, and
/// `.constructor.name` surface Proxy semantics — use duck typing / explicit
/// enumeration on the loaded value.
pub fn esm_index_to_cjs_lazy(esm_index: &str) -> String {
    let mut out = String::new();
    out.push_str("// Generated by dynwinrt-codegen \u{2014} do not edit\n");
    // `class {}` target avoids pinning `arguments`/`caller`/`prototype`.
    out.push_str("const __lazy = (load) => {\n");
    out.push_str("    const target = class {};\n");
    out.push_str("    const targetKeys = new Set(Reflect.ownKeys(target));\n");
    out.push_str("    return new Proxy(target, {\n");
    out.push_str("        get(t, prop) { return prop in Object(load()) ? Reflect.get(load(), prop) : Reflect.get(t, prop); },\n");
    out.push_str("        set(_, prop, value) { return Reflect.set(load(), prop, value); },\n");
    out.push_str("        construct(_, args) { return Reflect.construct(load(), args); },\n");
    out.push_str(
        "        apply(_, thisArg, args) { return Reflect.apply(load(), thisArg, args); },\n",
    );
    out.push_str(
        "        has(t, prop) { return prop in Object(load()) || Reflect.has(t, prop); },\n",
    );
    out.push_str("        ownKeys(t) {\n");
    out.push_str("            const loaded = load();\n");
    out.push_str(
        "            const loadedKeys = loaded != null ? Reflect.ownKeys(Object(loaded)) : [];\n",
    );
    out.push_str(
        "            return Array.from(new Set([...loadedKeys, ...Reflect.ownKeys(t)]));\n",
    );
    out.push_str("        },\n");
    out.push_str("        getOwnPropertyDescriptor(t, prop) {\n");
    out.push_str(
        "            if (targetKeys.has(prop)) return Reflect.getOwnPropertyDescriptor(t, prop);\n",
    );
    out.push_str("            const loaded = load();\n");
    out.push_str("            const d = loaded != null ? Reflect.getOwnPropertyDescriptor(Object(loaded), prop) : undefined;\n");
    out.push_str("            if (d) d.configurable = true;\n");
    out.push_str("            return d;\n");
    out.push_str("        },\n");
    out.push_str("        getPrototypeOf() { return Reflect.getPrototypeOf(Object(load())); },\n");
    out.push_str("    });\n");
    out.push_str("};\n");
    for line in esm_index.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with("//") {
            continue;
        }
        let (names, module) = match parse_index_export(trimmed) {
            Some(v) => v,
            None => continue,
        };
        for name in names {
            // Per-export memo slot: `require()` fires once per name on first access.
            out.push_str(&format!(
                "{{ let _m; exports.{name} = __lazy(() => (_m ??= require('./{module}.js')).{name}); }}\n",
                name = name,
                module = module
            ));
        }
    }
    out
}

/// ESM index → CJS barrel using memoised `Object.defineProperty` getters.
/// Returns real values (no Proxy) so `instanceof`/`===`/`.name` behave
/// naturally. Not visible to `cjs-module-lexer`, so this is only safe as the
/// `require()` entry point; the `import { X }` path goes through the
/// `index.mjs` ESM barrel. Use `esm_index_to_cjs_lazy` when a lexer-visible
/// CJS barrel is required.
pub fn esm_index_to_cjs_getter(esm_index: &str) -> String {
    let mut out = String::new();
    out.push_str("// Generated by dynwinrt-codegen \u{2014} do not edit\n");
    out.push_str(
        "const __exportLazy = (name, path) => {\n\
        \x20   let mod;\n\
        \x20   Object.defineProperty(exports, name, {\n\
        \x20       enumerable: true,\n\
        \x20       configurable: true,\n\
        \x20       get() { return (mod ??= require(path))[name]; },\n\
        \x20   });\n\
        };\n",
    );
    let mut all_names: Vec<String> = Vec::new();
    for line in esm_index.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with("//") {
            continue;
        }
        let (names, module) = match parse_index_export(trimmed) {
            Some(v) => v,
            None => continue,
        };
        for name in names {
            out.push_str(&format!(
                "__exportLazy('{name}', './{module}.js');\n",
                name = name,
                module = module,
            ));
            all_names.push(name.to_string());
        }
    }
    if !all_names.is_empty() {
        // Dead-code hint for cjs-module-lexer to discover named exports.
        out.push_str("0 && (module.exports = {\n");
        for name in &all_names {
            out.push_str(&format!("    {name},\n", name = name));
        }
        out.push_str("});\n");
    }
    out
}

/// Emit the ESM barrel. Re-exports are *eager* — the barrel loads every
/// sibling transitively; consumers who care about startup should use the
/// subpath exports from the generated `package.json` instead.
pub fn esm_index_to_esm(esm_index: &str) -> String {
    let mut out = String::new();
    out.push_str("// Generated by dynwinrt-codegen \u{2014} do not edit\n");
    // Import CJS namespaces and re-export from properties rather than using
    // `export { X } from './X.js'` directly: legacy index metadata can mention
    // helper aliases that don't exist in the CJS file, and re-export syntax
    // would fail the whole barrel at ESM link time. Property access lets
    // missing aliases resolve to `undefined` without breaking unrelated imports.
    let mut module_index = 0usize;
    for line in esm_index.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with("//") {
            continue;
        }
        let (names, module) = match parse_index_export(trimmed) {
            Some(v) => v,
            None => continue,
        };
        let module_var = format!("__m{}", module_index);
        module_index += 1;
        out.push_str(&format!(
            "import * as {} from './{}.js';\n",
            module_var, module
        ));
        for name in names {
            out.push_str(&format!("export const {0} = {1}.{0};\n", name, module_var));
        }
    }
    out
}

/// Parse a single `export { A, B, ... } from './Module.js';` line. Returns
/// (names, module_stem) or None if the line does not match.
fn parse_index_export(line: &str) -> Option<(Vec<String>, String)> {
    let line = line.trim().trim_end_matches(';');
    let rest = line.strip_prefix("export")?.trim_start();
    let rest = rest.strip_prefix('{')?;
    let close = rest.find('}')?;
    let names_str = &rest[..close];
    let after = rest[close + 1..].trim_start();
    let after = after.strip_prefix("from")?.trim_start();
    let (quote_char, source) = if let Some(rest) = after.strip_prefix('\'') {
        ('\'', rest)
    } else if let Some(rest) = after.strip_prefix('"') {
        ('"', rest)
    } else {
        return None;
    };
    let end_quote = source.find(quote_char)?;
    let source = &source[..end_quote];
    let module = source
        .trim_start_matches("./")
        .trim_end_matches(".js")
        .to_string();
    let names: Vec<String> = names_str
        .split(',')
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        .collect();
    if names.is_empty() {
        None
    } else {
        Some((names, module))
    }
}

// ======================================================================
// Public: append_to_index — merge new types into an existing ESM index
// ======================================================================

pub fn append_to_index(
    existing: &str,
    classes: &[ClassMeta],
    interfaces: &[InterfaceMeta],
    enums: &[TypeMeta],
) -> String {
    // Parse existing export lines to find already-exported names and modules
    let mut seen: HashSet<String> = HashSet::new();
    let mut exported_modules: HashSet<String> = HashSet::new();
    for line in existing.lines() {
        // Match: export { Foo } from './Foo.js';
        // Match: export { IID_IBar, IBar } from './IBar.js';
        if line.starts_with("export {") {
            if let Some(start) = line.find('{') {
                if let Some(end) = line.find('}') {
                    for name in line[start + 1..end].split(',') {
                        let name = name.trim();
                        if !name.is_empty() {
                            seen.insert(name.to_string());
                        }
                    }
                }
            }
            // Track module name from `from './Foo.js'`
            if let Some(start) = line.find("from './") {
                if let Some(end) = line[start + 8..].find("'") {
                    let module = &line[start + 8..start + 8 + end];
                    let module = module.strip_suffix(".js").unwrap_or(module);
                    exported_modules.insert(module.to_string());
                }
            }
        }
    }

    let mut out = existing.to_string();
    if !out.ends_with('\n') {
        out.push('\n');
    }

    // Add new classes with pack/unpack struct helpers
    let mut sorted_classes: Vec<_> = classes.iter().collect();
    sorted_classes.sort_by(|a, b| a.name.cmp(&b.name));
    for class in sorted_classes {
        if !exported_modules.contains(&class.name) && seen.insert(class.name.clone()) {
            let struct_names: Vec<_> = collect_used_structs_from_class(class)
                .iter()
                .flat_map(|s| ts_pack_export_names(s))
                .filter(|n| seen.insert(n.clone()))
                .collect();
            if struct_names.is_empty() {
                out.push_str(&format!(
                    "export {{ {} }} from './{}.js';\n",
                    class.name, class.name
                ));
            } else {
                out.push_str(&format!(
                    "export {{ {}, {} }} from './{}.js';\n",
                    class.name,
                    struct_names.join(", "),
                    class.name
                ));
            }
        }
    }

    // Add new interfaces with pack/unpack struct helpers (no IID_*)
    let mut sorted_ifaces: Vec<_> = interfaces.iter().collect();
    sorted_ifaces.sort_by(|a, b| a.name.cmp(&b.name));
    for iface in sorted_ifaces {
        if exported_modules.contains(&iface.name) || !seen.insert(iface.name.clone()) {
            continue;
        }
        // Skip delegates (IID + PARAM_TYPES only — internal plumbing)
        let is_delegate = iface.methods.iter().any(|m| m.name == ".ctor")
            && iface.methods.iter().any(|m| m.name == "Invoke");
        if is_delegate {
            continue;
        }
        let struct_names: Vec<_> = collect_used_structs_from_iface(iface)
            .iter()
            .flat_map(|s| ts_pack_export_names(s))
            .filter(|n| seen.insert(n.clone()))
            .collect();
        if struct_names.is_empty() {
            out.push_str(&format!("export {{ {0} }} from './{0}.js';\n", iface.name));
        } else {
            out.push_str(&format!(
                "export {{ {0}, {1} }} from './{0}.js';\n",
                iface.name,
                struct_names.join(", ")
            ));
        }
    }

    // Add new enums
    let mut sorted_enums: Vec<_> = enums.iter().collect();
    sorted_enums.sort_by(|a, b| {
        let name_a = match a {
            TypeMeta::Enum { name, .. } => name.as_str(),
            _ => "",
        };
        let name_b = match b {
            TypeMeta::Enum { name, .. } => name.as_str(),
            _ => "",
        };
        name_a.cmp(name_b)
    });
    for en in sorted_enums {
        if let TypeMeta::Enum { name, .. } = en {
            if !exported_modules.contains(name) && seen.insert(name.clone()) {
                out.push_str(&format!("export {{ {} }} from './{}.js';\n", name, name));
            }
        }
    }

    out
}

/// Returns only user-facing struct helpers (pack/unpack) for index re-export.
/// Excludes *_Type which is internal plumbing.
fn ts_pack_export_names(s: &TypeMeta) -> Vec<String> {
    match s {
        TypeMeta::Struct { name, .. } => vec![format!("pack{}", name), format!("unpack{}", name)],
        _ => vec![],
    }
}
