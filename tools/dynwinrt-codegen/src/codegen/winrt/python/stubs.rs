//! Generate Python `.pyi` stub files for IDE / type-checker support.
//! Stubs contain only type signatures; method bodies are `...`.
//! Implementation details (interface registration, struct helpers, IID
//! constants tied to runtime, factory activation) are not emitted.

use std::collections::HashSet;

use crate::meta::{ClassMeta, InterfaceMeta, MethodMeta};
use crate::types::{TypeKind, TypeMeta};

use crate::codegen::winrt::shared::imports::{
    collect_iface_type_imports, collect_type_imports, collect_used_generics_from_class,
    collect_used_generics_from_methods,
};
use crate::codegen::winrt::shared::structs::{
    collect_used_structs_from_class, collect_used_structs_from_iface,
};

use super::collections::{abc_name, class_interface, interface_kind};
use super::naming::{is_py_reserved, to_snake_case, to_snake_case_filename};
use super::shared::reorder_getters_before_setters;
use super::signature::py_dynwinrt_type;
use super::stub_helpers::{
    emit_method_stub, emit_method_stub_named, emit_static_method_stub,
    emit_static_method_stub_named, emit_struct_stub, format_py_type_import, py_struct_export_names,
};
use super::type_helpers::methods_have_async_output;

const HEADER: &str = "# Generated by dynwinrt-codegen — do not edit\n";
const FUTURE_ANNOTATIONS: &str = "from __future__ import annotations\n";
const IMPORT_LINE: &str = "\
from collections.abc import (
    Callable, Iterable, Iterator, Mapping, MutableMapping, MutableSequence, Sequence,
)
from datetime import datetime, timedelta
from uuid import UUID
from typing import overload
from dynwinrt_py import (
    DynWinRTType, DynWinRTValue, DynWinRTArray, DynWinRTStruct, DynWinRtDelegate, WinGUID,
)\n";
const ASYNC_IMPORT_LINE: &str = "from dynwinrt_py import WinRTAsync, WinRTAsyncWithProgress\n";

/// Generate a `.pyi` stub for an enum. Returns `None` for non-enum TypeMeta.
pub fn generate_enum_stub(en: &TypeMeta) -> Option<String> {
    let (name, members, is_flags) = match en {
        TypeMeta::Enum {
            name,
            members,
            is_flags,
            ..
        } => (name, members, *is_flags),
        _ => return None,
    };
    let mut out = String::new();
    out.push_str(HEADER);
    let enum_base = if is_flags { "IntFlag" } else { "IntEnum" };
    out.push_str(&format!("from enum import {enum_base}\n\n\n"));
    out.push_str(&format!("class {}({enum_base}):\n", name));
    if members.is_empty() {
        out.push_str("    pass\n");
    } else {
        for m in members {
            let member_name = if is_py_reserved(&m.name) {
                format!("{}_", m.name)
            } else {
                m.name.clone()
            };
            out.push_str(&format!("    {} = {}\n", member_name, m.value));
        }
    }
    Some(out)
}

/// Generate a `.pyi` stub for an interface (or a delegate).
pub fn generate_interface_stub(
    iface: &InterfaceMeta,
    known_types: &HashSet<String>,
    delegate_type_names: &HashSet<String>,
) -> String {
    let is_delegate = iface.methods.iter().any(|m| m.name == ".ctor")
        && iface.methods.iter().any(|m| m.name == "Invoke");
    if is_delegate {
        // Delegate stub: only IID + PARAM_TYPES declarations
        let mut out = String::new();
        out.push_str(HEADER);
        out.push_str(FUTURE_ANNOTATIONS);
        out.push_str("from dynwinrt_py import DynWinRTType, WinGUID\n\n");
        out.push_str(&format!("IID_{}: WinGUID\n", iface.name));
        out.push_str(&format!("{}_PARAM_TYPES: list[DynWinRTType]\n", iface.name));
        return out;
    }

    let used_structs = collect_used_structs_from_iface(iface);

    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str(FUTURE_ANNOTATIONS);
    out.push_str(IMPORT_LINE);
    let collection_kind = interface_kind(iface);
    if methods_have_async_output(iface.methods.iter()) {
        out.push_str(ASYNC_IMPORT_LINE);
    }
    if iface
        .methods
        .iter()
        .any(|method| method.is_event_add || method.is_event_remove)
    {
        out.push_str("from typing import Callable\n");
    }
    out.push('\n');

    let mut delegate_names: HashSet<String> = delegate_type_names.clone();
    for method in &iface.methods {
        for p in &method.params {
            if let TypeMeta::Delegate { name, .. } = &p.typ {
                delegate_names.insert(name.clone());
            }
            if method.is_event_add || method.is_event_remove {
                if let TypeMeta::Parameterized { name, args, .. } = &p.typ {
                    delegate_names.insert(crate::meta::make_parameterized_name(name, args));
                }
            }
        }
    }

    let collection_names = collect_used_generics_from_methods(&iface.methods);
    for cname in &collection_names {
        if cname != &iface.name && !delegate_names.contains(cname) {
            let module = to_snake_case_filename(cname);
            out.push_str(&format!(
                "from .{} import {}  # noqa: F401\n",
                module, cname
            ));
        }
    }

    let mut sorted_delegates: Vec<_> = delegate_names.iter().collect();
    sorted_delegates.sort();
    for dname in &sorted_delegates {
        let module = to_snake_case_filename(dname);
        out.push_str(&format!(
            "from .{module} import IID_{dname}, {dname}_PARAM_TYPES  # noqa: F401\n",
        ));
    }

    let type_imports = collect_iface_type_imports(iface);
    let mut sorted_type_imports: Vec<_> = type_imports.iter().collect();
    sorted_type_imports
        .sort_by(|a, b| (&a.namespace, &a.name, &a.kind).cmp(&(&b.namespace, &b.name, &b.kind)));
    for r in &sorted_type_imports {
        if known_types.contains(&r.name) && !delegate_names.contains(&r.name) {
            out.push_str(&format_py_type_import(&r.name, r.kind));
        }
    }
    out.push('\n');

    if iface.generic_piid.is_some() || !iface.iid.is_empty() {
        out.push_str(&format!("IID_{}: WinGUID\n", iface.name));
    }
    out.push('\n');

    for s in &used_structs {
        out.push_str(&emit_struct_stub(s));
        out.push('\n');
    }

    let collection_base =
        collection_kind
            .and_then(abc_name)
            .and_then(|abc| match iface.generic_args.as_slice() {
                [element] => Some(format!(
                    "{}[{}]",
                    abc,
                    super::type_helpers::py_return_type_safe(Some(element), known_types)
                )),
                [key, value] => Some(format!(
                    "{}[{}, {}]",
                    abc,
                    super::type_helpers::py_return_type_safe(Some(key), known_types),
                    super::type_helpers::py_return_type_safe(Some(value), known_types)
                )),
                _ => None,
            });
    if let Some(base) = collection_base {
        out.push_str(&format!("\nclass {}({base}):\n", iface.name));
    } else {
        out.push_str(&format!("\nclass {}:\n", iface.name));
    }
    out.push_str("    def __init__(self, obj: DynWinRTValue) -> None: ...\n");
    out.push_str(&collection_protocol_stubs(iface, known_types, 4));
    if !iface.iid.is_empty() || iface.generic_piid.is_some() {
        out.push('\n');
        out.push_str("    @staticmethod\n");
        out.push_str(&format!(
            "    def from_value(obj: DynWinRTValue) -> '{}': ...\n",
            iface.name
        ));
    }

    // IVector<T> / IMap<K,V> create()
    if let Some(ref piid) = iface.generic_piid {
        if piid == "913337e9-11a1-4345-a3a2-4e7f956e222d" && iface.generic_args.len() == 1 {
            let element =
                super::type_helpers::py_return_type_safe(Some(&iface.generic_args[0]), known_types);
            out.push('\n');
            out.push_str("    @staticmethod\n");
            out.push_str(&format!(
                "    def create(items: Iterable[{}]) -> '{}': ...\n",
                element, iface.name
            ));
        } else if piid == "3c2925fe-8519-45c1-aa79-197b6718c1c1" && iface.generic_args.len() == 2 {
            let key =
                super::type_helpers::py_return_type_safe(Some(&iface.generic_args[0]), known_types);
            let value =
                super::type_helpers::py_return_type_safe(Some(&iface.generic_args[1]), known_types);
            out.push('\n');
            out.push_str("    @staticmethod\n");
            out.push_str(&format!(
                "    def create(items: Mapping[{}, {}]) -> '{}': ...\n",
                key, value, iface.name
            ));
        }
    }

    for methods in super::overloads::grouped_methods(reorder_getters_before_setters(&iface.methods))
    {
        out.push('\n');
        out.push_str(&emit_instance_stub_group(
            &methods,
            known_types,
            &delegate_names,
            4,
        ));
    }

    out
}

/// Generate a `.pyi` stub for a runtime class.
pub fn generate_class_stub(
    class: &ClassMeta,
    known_types: &HashSet<String>,
    delegate_type_names: &HashSet<String>,
    shared_iids: &HashSet<String>,
) -> String {
    let used_structs = collect_used_structs_from_class(class);
    let collection_iface = class_interface(class);
    let collection_kind = collection_iface.and_then(interface_kind);
    let has_events = class.all_interfaces().any(|iface| {
        iface
            .methods
            .iter()
            .any(|method| method.is_event_add || method.is_event_remove)
    });

    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str(FUTURE_ANNOTATIONS);
    out.push_str(IMPORT_LINE);
    if methods_have_async_output(
        class
            .all_interfaces()
            .flat_map(|interface| interface.methods.iter()),
    ) {
        out.push_str(ASYNC_IMPORT_LINE);
    }
    if has_events {
        out.push_str("from typing import Callable\n");
    }
    if !class.required_interfaces.is_empty() {
        out.push_str("from typing import Type, TypeVar\n");
    }
    out.push('\n');

    let mut delegate_names: HashSet<String> = delegate_type_names.clone();
    for iface in class.all_interfaces() {
        for method in &iface.methods {
            for p in &method.params {
                if let TypeMeta::Delegate { name, .. } = &p.typ {
                    delegate_names.insert(name.clone());
                }
                if method.is_event_add || method.is_event_remove {
                    if let TypeMeta::Parameterized { name, args, .. } = &p.typ {
                        delegate_names.insert(crate::meta::make_parameterized_name(name, args));
                    }
                }
            }
        }
    }

    let collection_names = collect_used_generics_from_class(class);
    for cname in &collection_names {
        if !delegate_names.contains(cname) {
            let module = to_snake_case_filename(cname);
            out.push_str(&format!(
                "from .{} import {}  # noqa: F401\n",
                module, cname
            ));
        }
    }

    let mut sorted_delegates: Vec<_> = delegate_names.iter().collect();
    sorted_delegates.sort();
    for dname in &sorted_delegates {
        let module = to_snake_case_filename(dname);
        out.push_str(&format!(
            "from .{module} import IID_{dname}, {dname}_PARAM_TYPES  # noqa: F401\n",
        ));
    }

    let mut imported_names: HashSet<String> = HashSet::new();
    let imports = collect_type_imports(class);
    let mut sorted_imports: Vec<_> = imports.iter().collect();
    sorted_imports
        .sort_by(|a, b| (&a.namespace, &a.name, &a.kind).cmp(&(&b.namespace, &b.name, &b.kind)));
    for r in &sorted_imports {
        if known_types.contains(&r.name) && !delegate_names.contains(&r.name) {
            out.push_str(&format_py_type_import(&r.name, r.kind));
            imported_names.insert(r.name.clone());
            if r.kind == TypeKind::Interface {
                imported_names.insert(format!("IID_{}", r.name));
            }
        }
    }
    for req_iface in &class.required_interfaces {
        if req_iface.generic_piid.is_none()
            && !req_iface.iid.is_empty()
            && shared_iids.contains(&req_iface.iid)
            && !imported_names.contains(&req_iface.name)
        {
            out.push_str(&format_py_type_import(&req_iface.name, TypeKind::Interface));
            imported_names.insert(req_iface.name.clone());
            imported_names.insert(format!("IID_{}", req_iface.name));
        }
    }
    out.push('\n');
    if !class.required_interfaces.is_empty() {
        out.push_str("_InterfaceT = TypeVar('_InterfaceT')\n\n");
    }

    // IID constants (declarations only)
    for iface in class.all_interfaces() {
        let iid_name = format!("IID_{}", iface.name);
        if !iface.iid.is_empty() && !imported_names.contains(&iid_name) {
            out.push_str(&format!("{}: WinGUID\n", iid_name));
        }
    }
    out.push('\n');

    for s in &used_structs {
        out.push_str(&emit_struct_stub(s));
        out.push('\n');
    }

    let collection_base = collection_iface
        .zip(collection_kind.and_then(abc_name))
        .and_then(|(iface, abc)| match iface.generic_args.as_slice() {
            [element] => Some(format!(
                "{}[{}]",
                abc,
                super::type_helpers::py_return_type_safe(Some(element), known_types)
            )),
            [key, value] => Some(format!(
                "{}[{}, {}]",
                abc,
                super::type_helpers::py_return_type_safe(Some(key), known_types),
                super::type_helpers::py_return_type_safe(Some(value), known_types)
            )),
            _ => None,
        });
    if let Some(base) = collection_base {
        out.push_str(&format!("\nclass {}({base}):\n", class.name));
    } else {
        out.push_str(&format!("\nclass {}:\n", class.name));
    }
    out.push_str(&emit_constructor_stubs(class, known_types, &delegate_names));
    if let Some(collection_iface) = collection_iface {
        out.push_str(&collection_protocol_stubs(collection_iface, known_types, 4));
    }

    // Default constructor
    if class.has_default_constructor {
        let has_create_factory = class.factory_interfaces.iter().any(|iface| {
            iface.methods.iter().any(|m| {
                let snake = to_snake_case(&m.name);
                snake == "create" || snake.starts_with("create")
            })
        });
        let ctor_name = if has_create_factory {
            "create_default"
        } else {
            "create"
        };
        out.push('\n');
        out.push_str("    @staticmethod\n");
        out.push_str(&format!(
            "    def {}() -> '{}': ...\n",
            ctor_name, class.name
        ));
    }

    let static_methods = class
        .factory_interfaces
        .iter()
        .flat_map(|iface| iface.methods.iter().map(|method| (method, true)))
        .chain(
            class
                .static_interfaces
                .iter()
                .flat_map(|iface| iface.methods.iter().map(|method| (method, false))),
        )
        .collect::<Vec<_>>();
    for group in grouped_static_stubs(&static_methods) {
        out.push('\n');
        out.push_str(&emit_static_stub_group(
            &class.name,
            &group,
            known_types,
            delegate_type_names,
        ));
    }

    let instance_methods = class
        .default_interface
        .iter()
        .chain(class.required_interfaces.iter())
        .filter(|iface| iface.iid != "30d5a829-7fa4-4026-83bb-d75bae4ea99e")
        .flat_map(|iface| reorder_getters_before_setters(&iface.methods))
        .collect::<Vec<_>>();
    for methods in super::overloads::grouped_methods(instance_methods) {
        out.push('\n');
        out.push_str(&emit_instance_stub_group(
            &methods,
            known_types,
            &delegate_names,
            4,
        ));
    }
    // IClosable -> close()
    const ICLOSABLE_IID: &str = "30d5a829-7fa4-4026-83bb-d75bae4ea99e";
    if class
        .required_interfaces
        .iter()
        .any(|ri| ri.iid == ICLOSABLE_IID)
    {
        out.push('\n');
        out.push_str("    def close(self) -> None: ...\n");
        out.push_str(&format!(
            "    def __enter__(self) -> '{}': ...\n",
            class.name
        ));
        out.push_str(
            "    def __exit__(self, exc_type: object, exc_value: object, traceback: object) -> bool: ...\n",
        );
    }

    if !class.required_interfaces.is_empty() {
        out.push('\n');
        out.push_str(
            "    def as_interface(self, interface_class: Type[_InterfaceT]) -> _InterfaceT: ...\n",
        );
    }

    // Inline wrapper classes for required interfaces
    for req_iface in &class.required_interfaces {
        if req_iface.iid.is_empty() {
            continue;
        }
        if imported_names.contains(&req_iface.name) {
            continue;
        }
        out.push('\n');
        let required_base = interface_kind(req_iface)
            .and_then(abc_name)
            .and_then(|abc| match req_iface.generic_args.as_slice() {
                [element] => Some(format!(
                    "{}[{}]",
                    abc,
                    super::type_helpers::py_return_type_safe(Some(element), known_types)
                )),
                [key, value] => Some(format!(
                    "{}[{}, {}]",
                    abc,
                    super::type_helpers::py_return_type_safe(Some(key), known_types),
                    super::type_helpers::py_return_type_safe(Some(value), known_types)
                )),
                _ => None,
            });
        if let Some(base) = required_base {
            out.push_str(&format!("\nclass {}({base}):\n", req_iface.name));
        } else {
            out.push_str(&format!("\nclass {}:\n", req_iface.name));
        }
        out.push_str("    def __init__(self, obj: DynWinRTValue) -> None: ...\n");
        out.push_str(&collection_protocol_stubs(req_iface, known_types, 4));
        out.push('\n');
        out.push_str("    @staticmethod\n");
        out.push_str(&format!(
            "    def from_value(obj: DynWinRTValue) -> '{}': ...\n",
            req_iface.name
        ));
        for methods in
            super::overloads::grouped_methods(reorder_getters_before_setters(&req_iface.methods))
        {
            out.push('\n');
            out.push_str(&emit_instance_stub_group(
                &methods,
                known_types,
                &delegate_names,
                4,
            ));
        }
    }

    let _ = py_dynwinrt_type; // keep import referenced
    out
}

fn collection_protocol_stubs(
    iface: &InterfaceMeta,
    known_types: &HashSet<String>,
    indent_spaces: usize,
) -> String {
    let Some(kind) = interface_kind(iface) else {
        return String::new();
    };
    let indent = " ".repeat(indent_spaces);
    let item_type = iface
        .generic_args
        .first()
        .map(|typ| super::type_helpers::py_return_type_safe(Some(typ), known_types))
        .unwrap_or_else(|| "object".to_string());
    match kind {
        super::collections::CollectionKind::Iterable => {
            format!("\n{indent}def __iter__(self) -> Iterator[{item_type}]: ...\n")
        }

        super::collections::CollectionKind::Iterator => format!(
            "\n{indent}def __iter__(self) -> Iterator[{item_type}]: ...\n\
             {indent}def __next__(self) -> {item_type}: ...\n"
        ),
        super::collections::CollectionKind::Sequence
        | super::collections::CollectionKind::MutableSequence => {
            let mut result = format!(
                "\n{indent}def __len__(self) -> int: ...\n\
                 {indent}@overload\n\
                 {indent}def __getitem__(self, index: int) -> {item_type}: ...\n\
                 {indent}@overload\n\
                 {indent}def __getitem__(self, index: slice) -> list[{item_type}]: ...\n"
            );
            if kind == super::collections::CollectionKind::MutableSequence {
                result.push_str(&format!(
                    "{indent}def __setitem__(self, index: int | slice, value: {item_type} | Iterable[{item_type}]) -> None: ...\n\
                     {indent}def __delitem__(self, index: int | slice) -> None: ...\n\
                     {indent}def insert(self, index: int, value: {item_type}) -> None: ...\n"
                ));
            }
            result
        }
        super::collections::CollectionKind::Mapping
        | super::collections::CollectionKind::MutableMapping => {
            let key_type = item_type;
            let value_type = iface
                .generic_args
                .get(1)
                .map(|typ| super::type_helpers::py_return_type_safe(Some(typ), known_types))
                .unwrap_or_else(|| "object".to_string());
            let mut result = format!(
                "\n{indent}def __len__(self) -> int: ...\n\
                 {indent}def __iter__(self) -> Iterator[{key_type}]: ...\n\
                 {indent}def __getitem__(self, key: {key_type}) -> {value_type}: ...\n"
            );
            if kind == super::collections::CollectionKind::MutableMapping {
                result.push_str(&format!(
                    "{indent}def __setitem__(self, key: {key_type}, value: {value_type}) -> None: ...\n\
                     {indent}def __delitem__(self, key: {key_type}) -> None: ...\n"
                ));
            }
            result
        }
        super::collections::CollectionKind::KeyValuePair => String::new(),
    }
}

fn emit_constructor_stubs(
    class: &ClassMeta,
    known_types: &HashSet<String>,
    delegate_type_names: &HashSet<String>,
) -> String {
    let factory_methods = class
        .factory_interfaces
        .iter()
        .flat_map(|iface| iface.methods.iter())
        .collect::<Vec<_>>();
    let count = usize::from(class.has_default_constructor) + factory_methods.len();
    if count == 0 {
        return "    def __init__(self, obj: DynWinRTValue) -> None: ...\n".to_string();
    }

    let mut out = String::new();
    if class.has_default_constructor {
        if count > 1 {
            out.push_str("    @overload\n");
        }
        out.push_str("    def __init__(self) -> None: ...\n");
    }
    for method in factory_methods {
        if count > 1 {
            out.push_str("    @overload\n");
        }
        let in_params = crate::codegen::winrt::shared::imports::get_in_params(method);
        let params =
            super::type_helpers::py_param_list(&in_params, known_types, delegate_type_names);
        if params.is_empty() {
            out.push_str("    def __init__(self) -> None: ...\n");
        } else {
            out.push_str(&format!("    def __init__(self, {params}) -> None: ...\n"));
        }
    }
    out
}

fn emit_instance_stub_group(
    methods: &[&MethodMeta],
    known_types: &HashSet<String>,
    delegate_type_names: &HashSet<String>,
    indent_spaces: usize,
) -> String {
    if methods.len() == 1 {
        return emit_method_stub(methods[0], known_types, delegate_type_names, indent_spaces);
    }
    let names = super::overloads::method_names(methods.iter().copied());
    let public_name = super::overloads::method_group_key(methods[0], &names);
    let indent = " ".repeat(indent_spaces);
    methods
        .iter()
        .map(|method| {
            format!(
                "{indent}@overload\n{}",
                emit_method_stub_named(
                    method,
                    known_types,
                    delegate_type_names,
                    indent_spaces,
                    Some(&public_name),
                )
            )
        })
        .collect()
}

fn grouped_static_stubs<'a>(
    methods: &[(&'a MethodMeta, bool)],
) -> Vec<Vec<(&'a MethodMeta, bool)>> {
    let names = super::overloads::method_names(methods.iter().map(|(method, _)| *method));
    let mut groups: Vec<(String, Vec<(&MethodMeta, bool)>)> = Vec::new();
    for &(method, is_factory) in methods {
        let key = super::overloads::method_group_key(method, &names);
        if let Some((_, group)) = groups.iter_mut().find(|(name, _)| name == &key) {
            group.push((method, is_factory));
        } else {
            groups.push((key, vec![(method, is_factory)]));
        }
    }
    groups.into_iter().map(|(_, group)| group).collect()
}

fn emit_static_stub_group(
    class_name: &str,
    methods: &[(&MethodMeta, bool)],
    known_types: &HashSet<String>,
    delegate_type_names: &HashSet<String>,
) -> String {
    if methods.len() == 1 {
        let (method, is_factory) = methods[0];
        return emit_static_method_stub(
            class_name,
            method,
            known_types,
            is_factory,
            delegate_type_names,
        );
    }
    let names = super::overloads::method_names(methods.iter().map(|(method, _)| *method));
    let public_name = super::overloads::method_group_key(methods[0].0, &names);
    methods
        .iter()
        .map(|(method, is_factory)| {
            format!(
                "    @overload\n{}",
                emit_static_method_stub_named(
                    class_name,
                    method,
                    known_types,
                    *is_factory,
                    delegate_type_names,
                    Some(&public_name),
                )
            )
        })
        .collect()
}

/// Generate an `__init__.pyi` index stub.
pub fn generate_index_stub(
    classes: &[ClassMeta],
    interfaces: &[InterfaceMeta],
    enums: &[TypeMeta],
) -> String {
    let mut out = String::new();
    let mut seen: HashSet<String> = HashSet::new();
    out.push_str(HEADER);

    let mut sorted_classes: Vec<_> = classes.iter().collect();
    sorted_classes.sort_by(|a, b| a.name.cmp(&b.name));
    for class in sorted_classes {
        if seen.insert(class.name.clone()) {
            let struct_names: Vec<_> = collect_used_structs_from_class(class)
                .iter()
                .flat_map(|s| py_struct_export_names(s))
                .filter(|n| seen.insert(n.clone()))
                .collect();
            let module = to_snake_case_filename(&class.name);
            if struct_names.is_empty() {
                out.push_str(&format!(
                    "from .{} import {} as {}\n",
                    module, class.name, class.name
                ));
            } else {
                out.push_str(&format!(
                    "from .{} import {} as {}, {}\n",
                    module,
                    class.name,
                    class.name,
                    struct_names.join(", ")
                ));
            }
        }
    }

    let mut sorted_ifaces: Vec<_> = interfaces.iter().collect();
    sorted_ifaces.sort_by(|a, b| a.name.cmp(&b.name));
    for iface in sorted_ifaces {
        if !seen.insert(iface.name.clone()) {
            continue;
        }
        let is_delegate = iface.methods.iter().any(|m| m.name == ".ctor")
            && iface.methods.iter().any(|m| m.name == "Invoke");
        let module = to_snake_case_filename(&iface.name);
        if is_delegate {
            out.push_str(&format!(
                "from .{module} import IID_{iname}, {iname}_PARAM_TYPES\n",
                module = module,
                iname = iface.name
            ));
        } else {
            out.push_str(&format!(
                "from .{module} import IID_{iname}, {iname} as {iname}\n",
                module = module,
                iname = iface.name
            ));
        }
    }

    let mut sorted_enums: Vec<_> = enums.iter().collect();
    sorted_enums.sort_by(|a, b| {
        let na = match a {
            TypeMeta::Enum { name, .. } => name.as_str(),
            _ => "",
        };
        let nb = match b {
            TypeMeta::Enum { name, .. } => name.as_str(),
            _ => "",
        };
        na.cmp(nb)
    });
    for en in sorted_enums {
        if let TypeMeta::Enum { name, .. } = en {
            if seen.insert(name.clone()) {
                let module = to_snake_case_filename(name);
                out.push_str(&format!("from .{} import {} as {}\n", module, name, name));
            }
        }
    }
    out
}
