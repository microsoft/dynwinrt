"""Official-metadata regression for disposing a receiver inside invoke_detached.

Generate --namespace Microsoft.UI.Dispatching --class-name DispatcherQueue
--lang py from Microsoft.WindowsAppSDK.InteractiveExperiences 1.8.251104001,
metadata/10.0.18362.0/Microsoft.UI.winmd (SHA256
BA28DFC20E18630F3037AF2B91897082E41F1FA0E1DBB001D900505AB3577FE1),
with Windows SDK Windows.winmd as a reference. Pass the output to --generated.
The generated public IDispatcherQueue3 is used, not a handwritten replacement.
Select DispatcherQueue, not the ExclusiveTo interface directly: its required
interface dependencies expose this factory without widening visibility rules.

IDispatcherQueue3: 14a7a175-5c27-5a35-b079-21960cf764a8; IInspectable root;
no required interfaces. All eight contiguous HRESULT-returning ABI methods:
  6 EnqueueEventLoopExit()                       -> void
  7 EnsureSystemDispatcherQueue()                -> void
  8 RunEventLoop()                               -> void
  9 RunEventLoopWithOptions(in DispatcherRunOptions, in DispatcherExitDeferral)
                                                -> void
 10 add_FrameworkShutdownStarting(in TypedEventHandler<DispatcherQueue,
                                  DispatcherQueueShutdownStartingEventArgs>)
                                                -> out EventRegistrationToken
 11 remove_FrameworkShutdownStarting(in EventRegistrationToken) -> void
 12 add_FrameworkShutdownCompleted(in TypedEventHandler<DispatcherQueue, Object>)
                                                -> out EventRegistrationToken
 13 remove_FrameworkShutdownCompleted(in EventRegistrationToken) -> void
Slot 9 is metadata RunEventLoop with Overload("RunEventLoopWithOptions").
Options use the runtime's enumI32 representation for flags 0, 1, 2 (the raw
WinMD value__ field is UInt32); EventRegistrationToken is a single Int64.
The auxiliary deferral has IID 910b5aac-3310-563e-8418-f3005579729e, no
required interfaces, and exactly slot 6 Complete() -> void/HRESULT.

All receivers and the deferral are controlled standalone implementations.
Nothing activates a runtime class, bootstraps WinAppSDK, registers with the OS,
or runs a real event loop. No invocation monkeypatch, GC forcing, subprocess,
timeout adjustment, or forced process exit is used.
"""

from __future__ import annotations

