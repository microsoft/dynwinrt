import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageDir = fileURLToPath(new URL('..', import.meta.url))
const distDir = join(packageDir, 'dist')
const loader = readFileSync(join(distDir, 'index.js'), 'utf8')
const nativeExports = [
  ...loader.matchAll(/^module\.exports\.([A-Za-z_$][\w$]*) = nativeBinding\.\1$/gm),
].map((match) => match[1])

if (nativeExports.length === 0) {
  throw new Error('No N-API exports found in dist/index.js')
}

const comExports = new Set([
  'DynCom',
  'DynComInterface',
  'DynComMethodHandle',
  'DynComMethodSig',
  'DynComType',
  'DynWinRtValue',
  'DynWinRTValue',
  'WinGuid',
  'WinGUID',
])
const win32Exports = new Set(['DynWin32', 'DynWin32CallResult', 'DynWin32Value'])

writeFacade(
  'winrt',
  nativeExports.filter((name) => !name.startsWith('DynCom') && !name.startsWith('DynWin32')),
)
writeFacade(
  'com',
  nativeExports.filter((name) => comExports.has(name)),
)
writeFacade(
  'win32',
  nativeExports.filter((name) => win32Exports.has(name)),
)

function writeFacade(name, exports) {
  const required = name === 'com' ? comExports : name === 'win32' ? win32Exports : new Set()
  const missing = [...required].filter((value) => !exports.includes(value))
  if (missing.length > 0) {
    throw new Error(`Missing required ${name} exports: ${missing.join(', ')}`)
  }

  const js = [
    '// Generated by scripts/generate-entrypoints.mjs - do not edit',
    "'use strict'",
    "const native = require('./index.js')",
    ...exports.map((value) => `module.exports.${value} = native.${value}`),
    '',
  ].join('\n')
  const dts = [
    '// Generated by scripts/generate-entrypoints.mjs - do not edit',
    `export { ${exports.join(', ')} } from './index.js'`,
    '',
  ].join('\n')

  writeFileSync(join(distDir, `${name}.js`), js)
  writeFileSync(join(distDir, `${name}.d.ts`), dts)
}
